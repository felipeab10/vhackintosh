"""
vHackintosh — Internacionalização (pt-BR / en-US)

Decisão D1 do change `appliance-i18n-and-device-integration`: catálogos em
Python (dicts), uma chave por string, `t("chave", **fmt)`. Sem gettext/.po —
para dois idiomas o peso e o toolchain não se pagam.

O idioma fica em `~/.config/vhackintosh/settings.json` (campo `language`):
gravado pela primeira tela da instalação (quando ausente) e trocável depois
pelo script `vhackintosh-lang pt|en`. O default é `pt`: um appliance sem
registro nenhum continua falando português, que era o status quo.

Contrato de `t()`:
- idioma atual → catálogo daquele idioma → catálogo `pt` → a própria chave;
- `**fmt` vai para `str.format` (texto sem placeholders não liga);
- chave desconhecida devolve a chave visívelmente — um texto "quebrado" no
  meio da TUI é melhor que silêncio, e a varredura (task 2.6) apanha.
"""

from __future__ import annotations

import json
import os
import threading
from pathlib import Path
from typing import Optional

from core.config import CONFIG_DIR

SETTINGS_FILE = CONFIG_DIR / "settings.json"

# Códigos internos → rótulo mostrado na tela de idioma. Ordem: o primeiro é o
# default do appliance (pt-BR).
LANGUAGES: dict[str, str] = {
    "pt": "Português (Brasil)",
    "en": "English (US)",
}
DEFAULT_LANGUAGE = "pt"

_lock = threading.Lock()
_cache: dict = {}


def _load_settings() -> dict:
    if not _cache:
        try:
            with open(SETTINGS_FILE, "rb") as fh:
                data = json.load(fh)
            if isinstance(data, dict):
                _cache.update(data)
        except (OSError, ValueError):
            _cache.clear()
    return _cache


def save_settings(settings: dict) -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    with open(SETTINGS_FILE, "w", encoding="utf-8") as fh:
        json.dump(settings, fh, indent=2, ensure_ascii=False)
    _cache.clear()
    _cache.update(settings)


def get_language() -> str:
    """Idioma atual; 'pt' quando não registrado (default do appliance)."""
    lang = str(_load_settings().get("language", DEFAULT_LANGUAGE))
    return lang if lang in LANGUAGES else DEFAULT_LANGUAGE


def set_language(lang: str) -> None:
    if lang not in LANGUAGES:
        raise ValueError(
            f"idioma não suportado: {lang!r} (aceitos: {', '.join(LANGUAGES)})"
        )
    with _lock:
        settings = dict(_load_settings())
        settings["language"] = lang
        save_settings(settings)


def has_language_choice() -> bool:
    """True quando o idioma já foi escolhido (registrado no settings).

    A primeira tela da instalação só aparece enquanto isto for False — um
    appliance já instalado (com registro) direto abre a TUI.
    """
    return "language" in _load_settings()


