CATALOGS: dict[str, dict[str, str]] = {"pt": PT, "en": EN}


def register_catalog(lang: str, entries: dict[str, str]) -> None:
    """Funde chaves num catálogo (para módulos que carregam separadamente)."""
    if lang not in CATALOGS:
        raise ValueError(f"idioma desconhecido: {lang}")
    CATALOGS[lang].update(entries)


def t(key: str, **fmt) -> str:
    """Traduz `key` para o idioma atual, com formatação posicional nomeada."""
    lang = get_language()
    text = CATALOGS.get(lang, {}).get(key)
    if text is None:
        text = PT.get(key)
    if text is None:
        text = key
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, IndexError, ValueError):
            return text
    return text
