vhack_install_msg() {
  local key="$1"
  shift
  local template
  if [[ "${VHACK_INSTALL_LANGUAGE:-pt}" == "en" ]]; then
    template="${_VHACK_INSTALL_EN[$key]:-${_VHACK_INSTALL_PT[$key]:-$key}}"
  else
    template="${_VHACK_INSTALL_PT[$key]:-$key}"
  fi
  if (($#)); then
    printf "$template" "$@"
  else
    printf '%s' "$template"
  fi
}
